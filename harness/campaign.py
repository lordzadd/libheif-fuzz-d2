#!/usr/bin/env python3
"""D3 Track B: sustained libFuzzer campaign with coverage-over-time.

Each target runs in libFuzzer ``-fork`` mode so the campaign keeps going after a
sanitizer finding.  A campaign is split into fixed-length rounds; the corpus is
persisted between rounds and grows as libFuzzer finds new units.  For every
round we keep the raw libFuzzer log and parse its ``cov:`` status lines into a
coverage-over-time table.  Crash artifacts are de-duplicated by SHA-1.

Configuration (environment variables):
    D3_LABEL              label for the run, e.g. "baseline" (default: campaign)
    D3_ROUNDS             number of rounds per target          (default: 5)
    D3_ROUND_SECONDS      wall seconds per round               (default: 30)
    D3_WORKERS            libFuzzer -fork=N workers per target (default: 2)
    D3_MAX_PARALLEL       targets run at once                  (default: 3)
    D3_TIMEOUT_MARGIN     subprocess timeout margin in seconds (default: 30)

No real user data is used.  Every input is either an upstream synthetic test
fixture in libheif/fuzzing/data/corpus or a mutation generated by libFuzzer.
"""

import csv
import datetime as dt
import hashlib
import json
import os
import re
import resource
import shutil
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FUZZ_DIR = ROOT / "build" / "fuzzing"
SEED_SRC = ROOT / "libheif" / "fuzzing" / "data" / "corpus"
FUZZERS = (
    "api_fuzzer", "box_fuzzer", "color_conversion_fuzzer", "encoder_fuzzer",
    "file_fuzzer", "sequence_fuzzer", "tile_fuzzer",
)

COV_RE = re.compile(
    r"^#(?P<unit>\d+):\s+cov:\s*(?P<cov>\d+)\s+ft:\s*(?P<ft>\d+)"
    r"\s+corp:\s*(?P<corp>\d+).*?time:\s*(?P<time>\d+)s"
)


def env_int(name, default):
    try:
        return int(os.environ.get(name, str(default)))
    except ValueError:
        return default


def tool_versions():
    def first_line(cmd):
        try:
            return subprocess.run(
                cmd, shell=True, capture_output=True, text=True, timeout=20
            ).stdout.strip().splitlines()[0]
        except Exception:
            return "unknown"
    return {
        "clang": first_line("clang++ --version"),
        "cmake": first_line("cmake --version"),
        "python": sys.version.split()[0],
        "kernel": first_line("uname -sr"),
        "cpu_count_logical": os.cpu_count(),
    }


def parse_cov(log_text):
    """Return all cov status samples as dicts (one per libFuzzer status line)."""
    samples = []
    for line in log_text.splitlines():
        m = COV_RE.match(line)
        if m:
            samples.append({
                "unit": int(m.group("unit")),
                "cov_edges": int(m.group("cov")),
                "ft": int(m.group("ft")),
                "corp": int(m.group("corp")),
                "local_time_s": int(m.group("time")),
            })
    return samples


def seed_corpus(dest):
    dest.mkdir(parents=True, exist_ok=True)
    count = 0
    if SEED_SRC.is_dir():
        for src in SEED_SRC.rglob("*"):
            if src.is_file():
                dst = dest / src.relative_to(SEED_SRC)
                dst.parent.mkdir(parents=True, exist_ok=True)
                if not dst.exists():
                    shutil.copy2(src, dst)
                count += 1
    return count


def unique_artifacts(art_dir):
    """Map sha1 -> artifact path for crash/oom/timeout files."""
    found = {}
    if not art_dir.is_dir():
        return found
    for path in art_dir.iterdir():
        if path.is_file() and path.name.startswith(("crash-", "oom-", "timeout-")):
            digest = hashlib.sha1(path.read_bytes()).hexdigest()
            found.setdefault(digest, path)
    return found


def run_round(name, fuzzer, round_no, corpus, artifacts, log_path, seconds,
              workers, timeout):
    command = [
        str(fuzzer), str(corpus),
        "-fork=" + str(workers),
        "-ignore_crashes=1", "-ignore_timeouts=1", "-ignore_ooms=1",
        "-max_total_time=" + str(seconds),
        "-print_final_stats=1",
        "-artifact_prefix=" + str(artifacts) + "/",
    ]
    started = time.monotonic()
    timed_out = False
    try:
        proc = subprocess.run(
            command, capture_output=True, text=True, errors="replace",
            timeout=timeout, cwd=ROOT,
        )
        rc = proc.returncode
        log = (proc.stdout or "") + "\n" + (proc.stderr or "")
    except subprocess.TimeoutExpired as error:
        timed_out = True
        rc = None
        out = error.stdout or b""
        err = error.stderr or b""
        log = (out if isinstance(out, str) else out.decode("utf-8", "replace"))
        log += "\n" + (err if isinstance(err, str) else err.decode("utf-8", "replace"))
    elapsed = round(time.monotonic() - started, 2)
    log_path.parent.mkdir(parents=True, exist_ok=True)
    log_path.write_text(log, errors="replace")

    samples = parse_cov(log)
    corpus_files = sum(1 for p in corpus.rglob("*") if p.is_file())
    uniq = unique_artifacts(artifacts)
    row = {
        "fuzzer": name, "round": round_no, "wall_s": elapsed,
        "cov_edges": max((s["cov_edges"] for s in samples), default=0),
        "ft": max((s["ft"] for s in samples), default=0),
        "corpus_files": corpus_files,
        "unique_crashes": len(uniq),
        "cov_samples": len(samples),
        "exit_code": rc, "timed_out": timed_out,
        "log": str(log_path.relative_to(ROOT)),
    }
    tagged = []
    for s in samples:
        tagged.append({
            "fuzzer": name,
            "round": round_no,
            "global_time_s": None,  # filled by main after wall times are known
            "local_time_s": s["local_time_s"],
            "unit": s["unit"],
            "cov_edges": s["cov_edges"],
            "ft": s["ft"],
            "corp": s["corp"],
        })
    return row, tagged


def coverage_report(name, fuzzer, corpus, out_path, crash_hashes):
    """Capture libFuzzer -print_coverage=1 on the final, crash-free corpus.

    Fork-mode libFuzzer can keep a crash-triggering unit in the corpus; replaying
    it without fork aborts before coverage is printed, so we filter those units.
    """
    clean = out_path.parent / ("clean_corpus_" + name)
    if clean.exists():
        shutil.rmtree(clean)
    clean.mkdir(parents=True)
    kept = 0
    removed = 0
    for src in corpus.rglob("*"):
        if not src.is_file():
            continue
        if hashlib.sha1(src.read_bytes()).hexdigest() in crash_hashes:
            removed += 1
            continue
        shutil.copy2(src, clean / src.name)
        kept += 1
    art = out_path.parent / ("artifacts_" + name)
    art.mkdir(parents=True, exist_ok=True)
    command = [
        str(fuzzer), str(clean), "-runs=1", "-print_coverage=1",
        "-artifact_prefix=" + str(art) + "/",
    ]
    try:
        proc = subprocess.run(
            command, capture_output=True, text=True, errors="replace",
            timeout=120, cwd=ROOT,
        )
        text = (proc.stdout or "") + "\n" + (proc.stderr or "")
        rc = proc.returncode
    except subprocess.TimeoutExpired as error:
        text = "TIMEOUT\n"
        rc = None
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(text, errors="replace")
    covered = sum(1 for line in text.splitlines() if line.startswith("COVERED_FUNC:"))
    uncovered = sum(1 for line in text.splitlines() if line.startswith("UNCOVERED_FUNC:"))
    return covered, uncovered, rc, str(out_path.relative_to(ROOT)), kept, removed


def main():
    label = os.environ.get("D3_LABEL", "campaign")
    rounds = env_int("D3_ROUNDS", 5)
    seconds = env_int("D3_ROUND_SECONDS", 30)
    workers = env_int("D3_WORKERS", 2)
    parallel = env_int("D3_MAX_PARALLEL", 3)
    margin = env_int("D3_TIMEOUT_MARGIN", 30)
    if min(rounds, seconds, workers, parallel) < 1:
        print("error: round/worker settings must be positive", file=sys.stderr)
        return 2

    stamp = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    out = ROOT / "results" / "d3" / (label + "-" + stamp)
    out.mkdir(parents=True)
    (out / "logs").mkdir()
    (out / "corpora").mkdir()
    (out / "artifacts").mkdir()
    (out / "coverage").mkdir()

    missing = [n for n in FUZZERS if not (FUZZ_DIR / n).is_file()]
    if missing:
        print("error: missing fuzz binaries (run scripts/build.sh first): " + ", ".join(missing),
              file=sys.stderr)
        return 2

    # Provenance canary: proves the campaign used only synthetic data and lets
    # a reader check that no real user data entered any raw-result directory.
    (out / "CANARY.txt").write_text(
        "D3 Track B synthetic-data canary\n"
        "run: " + label + "-" + stamp + "\n"
        "token: D3-SYNTHETIC-CANARY-libheif-08075aeb-NOT-USER-DATA\n"
        "All inputs in this directory are either upstream synthetic test fixtures\n"
        "from libheif/fuzzing/data/corpus or libFuzzer mutations of them.\n"
    )

    config = {
        "label": label, "timestamp_utc": stamp,
        "target_commit": (ROOT / "libheif" / "UPSTREAM_COMMIT").read_text().strip(),
        "rounds": rounds, "round_seconds": seconds,
        "fork_workers_per_target": workers, "max_parallel_targets": parallel,
        "nominal_cores_busy": workers * parallel,
        "fuzzers": list(FUZZERS), "versions": tool_versions(),
        "corpus_source": str(SEED_SRC.relative_to(ROOT)),
        "sanitizers": "address,undefined,shift,integer with -fno-sanitize-recover",
        "output_dir": str(out.relative_to(ROOT)),
    }
    (out / "config.json").write_text(json.dumps(config, indent=2) + "\n")

    # Seed every corpus before starting; corpora persist across rounds.
    seed_counts = {}
    for name in FUZZERS:
        seed_counts[name] = seed_corpus(out / "corpora" / name)
    config["seed_counts"] = seed_counts
    (out / "config.json").write_text(json.dumps(config, indent=2) + "\n")

    rows = []
    cov_samples = []
    cpu_before = resource.getrusage(resource.RUSAGE_CHILDREN)
    wall_before = time.monotonic()

    def run_target(name):
        mine = []
        mine_cov = []
        fuzzer = FUZZ_DIR / name
        corpus = out / "corpora" / name
        artifacts = out / "artifacts" / name
        artifacts.mkdir(parents=True, exist_ok=True)
        for rnd in range(1, rounds + 1):
            log_path = out / "logs" / name / ("round_%02d.log" % rnd)
            row, tagged = run_round(
                name, fuzzer, rnd, corpus, artifacts, log_path,
                seconds, workers, seconds + margin,
            )
            mine.append(row)
            mine_cov.extend(tagged)
            print("  %-25s round %d/%d cov=%d crashes=%d" %
                  (name, rnd, rounds, row["cov_edges"], row["unique_crashes"]),
                  flush=True)
        return mine, mine_cov

    with ThreadPoolExecutor(max_workers=parallel) as pool:
        futures = {pool.submit(run_target, name): name for name in FUZZERS}
        for fut in as_completed(futures):
            r, c = fut.result()
            rows.extend(r)
            cov_samples.extend(c)

    cpu_after = resource.getrusage(resource.RUSAGE_CHILDREN)
    wall_total = round(time.monotonic() - wall_before, 2)
    cpu_total = round(
        (cpu_after.ru_utime - cpu_before.ru_utime)
        + (cpu_after.ru_stime - cpu_before.ru_stime), 2
    )

    rows.sort(key=lambda r: (r["fuzzer"], r["round"]))
    # Attach global timestamps from each round's measured wall duration.
    round_wall = {(r["fuzzer"], r["round"]): r["wall_s"] for r in rows}
    for s in cov_samples:
        base = sum(
            v for (n, rnd), v in round_wall.items()
            if n == s["fuzzer"] and rnd < s["round"]
        )
        s["global_time_s"] = round(base + min(s["local_time_s"], round_wall.get(
            (s["fuzzer"], s["round"]), s["local_time_s"])), 2)
    cov_samples.sort(key=lambda s: (s["fuzzer"], s["global_time_s"]))

    with (out / "campaign.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    with (out / "coverage_over_time.csv").open("w", newline="", encoding="utf-8") as fh:
        fields = ["fuzzer", "round", "global_time_s", "local_time_s", "unit",
                  "cov_edges", "ft", "corp"]
        w = csv.DictWriter(fh, fieldnames=fields)
        w.writeheader()
        w.writerows(cov_samples)

    # Function-level coverage on the final corpus (sequential: cheap).
    # Build the crash hash set before the coverage loop.
    all_crash_hashes = set()
    for name in FUZZERS:
        all_crash_hashes.update(unique_artifacts(out / "artifacts" / name).keys())
    cov_rows = []
    for name in FUZZERS:
        c, u, rc, path, kept, removed = coverage_report(
            name, FUZZ_DIR / name, out / "corpora" / name,
            out / "coverage" / (name + ".txt"), all_crash_hashes,
        )
        cov_rows.append({
            "fuzzer": name, "covered_funcs": c, "uncovered_funcs": u,
            "exit_code": rc, "report": path,
            "corpus_files_replayed": kept, "crash_units_filtered": removed,
        })
        print("  %-25s covered_funcs=%d uncovered_funcs=%d" % (name, c, u), flush=True)
    with (out / "coverage_functions.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(cov_rows[0]))
        w.writeheader()
        w.writerows(cov_rows)

    artifact_index = []
    for name in FUZZERS:
        for digest, path in sorted(unique_artifacts(out / "artifacts" / name).items()):
            artifact_index.append({
                "sha1": digest, "fuzzer": name,
                "path": str(path.relative_to(ROOT)),
                "bytes": path.stat().st_size,
            })

    summary = {
        "label": label,
        "campaign_wall_s": wall_total,
        "campaign_cpu_s": cpu_total,
        "cpu_hours": round(cpu_total / 3600.0, 4),
        "nominal_cores_busy": workers * parallel,
        "total_rounds": len(rows),
        "rounds_per_target": rounds,
        "round_seconds": seconds,
        "unique_crash_inputs": len(artifact_index),
        "crash_index": artifact_index,
        "final_coverage_by_fuzzer": {
            r["fuzzer"]: max(x["cov_edges"] for x in rows if x["fuzzer"] == r["fuzzer"])
            for r in rows
        },
        "coverage_function_totals": {
            "covered": sum(x["covered_funcs"] for x in cov_rows),
            "uncovered": sum(x["uncovered_funcs"] for x in cov_rows),
        },
        "config": config,
        "csv": str((out / "campaign.csv").relative_to(ROOT)),
        "coverage_csv": str((out / "coverage_over_time.csv").relative_to(ROOT)),
    }
    (out / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    print(json.dumps({
        "output_dir": str(out.relative_to(ROOT)),
        "wall_s": wall_total, "cpu_s": cpu_total,
        "cpu_hours": summary["cpu_hours"],
        "unique_crashes": len(artifact_index),
    }, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
